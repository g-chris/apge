"""
__GAME_TITLE__ - game rules.

Starter game generated by APGE: each round everyone answers a prompt, then votes for
their favourite answer (anonymously, and not their own). 100 points per vote.
Replace the prompts and phases with your own game.
"""
import random

from apge import Game, Reject, action, on_all_ready, on_timeout, phase

PROMPTS = [
    'The worst thing to say on a first date',
    'A terrible name for a boat',
    'What the cat is actually thinking',
    'The real reason the dinosaurs died out',
    'A rejected flavour of crisps',
    'The worst superpower to have',
]
ROUNDS = 3
POINTS_PER_VOTE = 100


class HotTake(Game):
    title = '__GAME_TITLE__'
    min_players = 2
    max_players = 10

    # ---- setup ---------------------------------------------------------------

    def on_start(self):
        self.prompts = random.sample(PROMPTS, ROUNDS)
        self.public.update(round=0, rounds=ROUNDS)
        for p in self.players.values():
            p.public['score'] = 0
        self.next_round()

    def next_round(self):
        self.public['round'] += 1
        self.public['prompt'] = self.prompts[self.public['round'] - 1]
        for p in self.players.values():
            p.private = {}
            p.public['answered'] = False
            p.public['voted'] = False
        self.goto('write')

    # ---- write: everyone answers the prompt ------------------------------------

    @phase('write', timer=60)
    def enter_write(self):
        self.public.pop('answers', None)
        self.public.pop('results', None)

    @action('answer', phases='write')
    def answer(self, player, data):
        text = ' '.join(str(data.get('text', '')).split())[:80]
        if not text:
            raise Reject('Type an answer first!')
        if 'answer' in player.private:
            raise Reject('You already answered.')
        player.private['answer'] = text
        player.public['answered'] = True
        # Disconnected players don't hold the round up; the timer covers them
        if self.everyone(lambda p: p.public['answered'], include_disconnected=False):
            self.goto('vote')

    @on_timeout('write')
    def write_timeout(self):
        self.goto('vote')

    # ---- vote: answers are shown without names -----------------------------------

    @phase('vote', timer=30)
    def enter_vote(self):
        answered = [p for p in self.players.values() if 'answer' in p.private]
        random.shuffle(answered)
        # Authors stay secret (server-side) until the reveal
        self.authors = {}
        self.public['answers'] = []
        for i, p in enumerate(answered):
            self.authors[i] = p.id
            p.private['answer_id'] = i
            self.public['answers'].append({'id': i, 'text': p.private['answer']})
        if not any(self.can_vote(p) for p in self.players.values()):
            self.goto('reveal')

    def can_vote(self, player):
        return any(a['id'] != player.private.get('answer_id') for a in self.public['answers'])

    @action('vote', phases='vote')
    def vote(self, player, data):
        choice = data.get('answer')
        if not isinstance(choice, int) or isinstance(choice, bool) or choice not in self.authors:
            raise Reject('Pick one of the answers.')
        if choice == player.private.get('answer_id'):
            raise Reject("You can't vote for your own answer!")
        if 'vote' in player.private:
            raise Reject('You already voted.')
        player.private['vote'] = choice
        player.public['voted'] = True
        if self.everyone(lambda p: p.public['voted'] or not self.can_vote(p), include_disconnected=False):
            self.goto('reveal')

    @on_timeout('vote')
    def vote_timeout(self):
        self.goto('reveal')

    # ---- reveal: scores, then everyone presses Continue ----------------------------

    @phase('reveal', timer=15, ready=True)
    def enter_reveal(self):
        votes = {a['id']: 0 for a in self.public['answers']}
        for p in self.players.values():
            if 'vote' in p.private:
                votes[p.private['vote']] += 1
        results = []
        for a in self.public['answers']:
            author = self.players[self.authors[a['id']]]
            author.public['score'] += votes[a['id']] * POINTS_PER_VOTE
            results.append({'text': a['text'], 'author': author.name, 'votes': votes[a['id']]})
        self.public['results'] = sorted(results, key=lambda r: -r['votes'])

    @on_all_ready('reveal')
    def reveal_done(self):
        if self.public['round'] < ROUNDS:
            self.next_round()
        else:
            self.goto('game_over')

    # ---- game over -------------------------------------------------------------------

    @phase('game_over')
    def enter_game_over(self):
        standings = sorted(self.players.values(), key=lambda p: -p.public['score'])
        self.public['standings'] = [{'name': p.name, 'score': p.public['score']} for p in standings]
